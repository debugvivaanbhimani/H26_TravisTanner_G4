def render_markdown(doc: dict) -> str:
    s = doc["summary"]
    L = [f"# Dependency Exit Capsule — {doc['target_repository'].get('remote') or doc['target_repository'].get('input')}",
         "",
         f"Commit `{doc['target_repository'].get('commit')}` · Python {doc['python_target']} · "
         f"generated {doc['finished_at']} by {doc['generated_by']['name']} {doc['generated_by']['version']}",
         ""]
    if doc.get("ai_model"):
        m = doc["ai_model"]
        L += [f"**AI model:** `{m['name']}` via {m['provider']} ({m['endpoint']}). {m['terms']}", ""]
    L += ["## How to read this capsule", ""]
    for k, v in doc["provenance_legend"].items():
        L.append(f"- **[{k}]** {v}")
    b = s["baseline_tests"]
    L += ["", "## Summary", "",
          f"- Dependencies analysed: **{s['dependencies_analysed']}** "
          f"(observed risk: {s['observed_risk']['high']} high, {s['observed_risk']['medium']} medium, {s['observed_risk']['low']} low)",
          f"- [VERIFIED] Baseline test run with original dependencies: **{b.get('passed', 0)} passed, "
          f"{b.get('failed', 0) + b.get('error', 0)} failed** of {b.get('total', 0)}",
          f"- [VERIFIED] Migrations verified: **{s['migrations_verified']} / {s['migrations_attempted']}** attempted",
          ]
    if s.get("combined_tests"):
        c = s["combined_tests"]
        L.append(f"- [VERIFIED] All verified migrations applied together: **{c.get('passed', 0)} passed, "
                 f"{c.get('failed', 0) + c.get('error', 0)} failed** of {c.get('total', 0)}")
    L += [f"- [OBSERVED] AI outputs failing the grounding check: {s['ai_ungrounded_claims']}", ""]

    L += ["## Overview", "", "| Dependency | Observed risk | AI action | Replacement | Verification |",
          "|---|---|---|---|---|"]
    for c in doc["capsules"]:
        ai = c["ai_recommendation"] or {}
        rep = (ai.get("proposed_replacement") or {})
        rep_s = f"{rep.get('package') or ''} {rep.get('version_spec') or ''}".strip() or "—"
        L.append(f"| `{c['dependency']}` | {c['observed']['observed_risk']} | {ai.get('action', '—')} | {rep_s} | {c['status']} |")

    for c in doc["capsules"]:
        o = c["observed"]
        d = o["dependency_details"]
        L += ["", f"## `{c['dependency']}` — {c['status']}", "", "### Dependency details [OBSERVED]", ""]
        for dd in d["declared"]:
            L.append(f"- Declared `{dd['raw']}` in `{dd['file']}`" + (f":{dd['line']}" if dd.get("line") else "") + f" ({dd['group']})")
        if not d["declared"]:
            L.append("- **Not declared in any manifest**")
        L.append(f"- Installed in baseline: `{d['installed_version_in_baseline']}` · latest on PyPI: "
                 f"`{d['latest_version']}` ({d['latest_released']}) · import names: {', '.join(d['import_names']) or '—'}")
        L += ["", "### Risk indicators [OBSERVED]", ""]
        for i in o["risk_indicators"] or []:
            L.append(f"- `{i['id']}` **{i['severity']}** — {i['detail']} _(source: {i['source']})_")
        if not o["risk_indicators"]:
            L.append("- none")
        L += ["", "### Usage locations [OBSERVED]", ""]
        for u in o["usage_locations"][:30] or []:
            L.append(f"- `{u['file']}:{u['line']}` [{u['kind']}] `{u['code']}`")
        if not o["usage_locations"]:
            L.append("- not imported by repository source")
        ai = c["ai_recommendation"]
        if ai:
            rep = ai.get("proposed_replacement") or {}
            L += ["", "### Proposed replacement & migration [AI]", "",
                  f"- Risk (AI): **{ai.get('risk_level')}** — {ai.get('risk_summary')}",
                  f"- Action: **{ai.get('action')}** → `{rep.get('package')}` `{rep.get('version_spec') or ''}`",
                  f"- Rationale: {ai.get('rationale')}", f"- Confidence: {ai.get('confidence')}", "", "Migration steps:"]
            L += [f"{n}. {s_}" for n, s_ in enumerate(ai.get("migration_steps") or [], 1)]
            L += ["", "Suggested tests:"] + [f"- {t}" for t in ai.get("suggested_tests") or []]
        v = c["ai_claim_verification"]
        if v:
            L += ["", "### Checks on the AI output [OBSERVED]", "",
                  f"- Grounded: **{v.get('grounded')}** · valid citations: {v.get('cited_indicator_ids_valid')} · "
                  f"invalid citations: {v.get('cited_indicator_ids_invalid')}",
                  f"- Replacement check: {v.get('replacement_check', 'n/a')}"]
        ex = c["execution"]
        if ex:
            cmp = ex.get("comparison") or {}
            L += ["", "### Executed test results [VERIFIED]", "",
                  f"- Original dependency (baseline): {_fmt(ex['baseline_original'])}",
                  f"- AI equivalence test on ORIGINAL code: {_fmt(ex.get('equivalence_test_on_original'))}",
                  f"- Replacement (project's own tests): {_fmt(ex.get('candidate_replacement'))}",
                  f"- AI equivalence test on REPLACEMENT: {_fmt(ex.get('equivalence_test_on_replacement'))}"
                  f" (valid: {ex.get('equivalence_test_valid')})",
                  f"- Verdict: **{cmp.get('verdict')}** · fixed: {cmp.get('fixed')} · regressed: "
                  f"{[r['test'] for r in cmp.get('regressed', [])]}",
                  f"- AI fix attempts used: {ex.get('fix_attempts')}",
                  f"- Patch: `{ex.get('patch_file')}` · equivalence test: `{ex.get('equivalence_test_file')}`"]
        g = c["compatibility_gaps"]
        L += ["", "### Compatibility gaps", "", "Observed [VERIFIED]:"]
        L += [f"- {x['type']}: {x.get('test', '')} {x.get('detail', '')}".strip() for x in g["observed"]["items"]] or ["- none observed"]
        L += ["", "Expected by AI [AI]:"]
        L += [f"- {x}" for x in g["expected_by_ai"]["items"]] or ["- none"]
        L += ["", "### Open concerns & limitations", ""]
        L += [f"- {x}" for x in c["open_concerns_and_limitations"]] or ["- none"]

    L += ["", "## Reproduce", ""] + [f"{n}. `{s_}`" for n, s_ in enumerate(doc["reproduce"]["steps"], 1)]
    L += ["", "Or run `./replay.sh` from this folder."]
    return "\n".join(L) + "\n"


def _fmt(s):
    if not s:
        return "not run"
    return f"{s.get('passed', 0)} passed, {s.get('failed', 0) + s.get('error', 0)} failed, {s.get('skipped', 0)} skipped (of {s.get('total', 0)})"
