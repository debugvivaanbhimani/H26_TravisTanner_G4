"""Dependency Exit Capsule writer.

Every field is tagged with its provenance:
  OBSERVED  - read from files, the AST, PyPI or GitHub (deterministic)
  VERIFIED  - produced by actually installing and executing code
  AI        - generated by Gemma; a recommendation, not a fact
"""
from __future__ import annotations

import json
from pathlib import Path

from .report_html import render_html

PROVENANCE = {
    "OBSERVED": "Read directly from repository files, the Python AST, PyPI or GitHub. Deterministic.",
    "VERIFIED": "Produced by installing dependencies in an isolated environment and executing code/tests.",
    "AI": "Generated by Gemma 4. A recommendation or hypothesis — not a verified fact.",
}


def _gaps_observed(mig: dict | None) -> list[dict]:
    if not mig or not mig.get("attempts"):
        return []
    last = mig["attempts"][-1]
    cmp, gaps = last["comparison"], []
    run = last.get("candidate_run") or {}
    if not run.get("install_ok"):
        gaps.append({"type": "install_failure", "detail": (run.get("install_error") or "")[-600:]})
    for r in cmp.get("regressed", []):
        gaps.append({"type": "regression", "test": r["test"], "detail": r["message"]})
    for r in cmp.get("new_tests", []):
        if r["status"] in ("failed", "error"):
            gaps.append({"type": "behaviour_changed", "test": r["test"], "detail": r["message"]})
    for r in cmp.get("still_failing", []):
        gaps.append({"type": "preexisting_failure_not_fixed", "test": r["test"], "detail": r["message"]})
    if last.get("equivalence_valid_on_original") is False:
        gaps.append({"type": "ai_equivalence_test_invalid",
                     "detail": "The AI-written equivalence test fails on the ORIGINAL code, so it was discarded "
                               "and proves nothing; verification relies on the project's own tests only."})
    if last.get("equivalence_passed_on_replacement") is False:
        gaps.append({"type": "behaviour_changed",
                     "detail": "The AI equivalence test passes on the original but FAILS on the replacement."})
    for e in last.get("edits", []):
        if not e.get("applied"):
            gaps.append({"type": "edit_not_applied", "detail": f"{e['file']}: {e.get('reason')}"})
    return gaps


def _concerns(dep, ai, chk, mig) -> list[str]:
    c = []
    if not ai:
        c.append("No AI analysis was produced for this dependency.")
    if chk.get("cited_indicator_ids_invalid"):
        c.append(f"AI cited evidence that does not exist: {chk['cited_indicator_ids_invalid']} — treat its reasoning with caution.")
    if chk.get("uncited_high_indicators"):
        c.append(f"AI did not address these high-severity observed indicators: {chk['uncited_high_indicators']}.")
    if chk.get("replacement_exists") is False:
        c.append(f"Proposed replacement could not be found ({chk.get('replacement_check')}).")
    if ai and (ai.get("confidence") or 1) < 0.6:
        c.append(f"AI confidence is low ({ai.get('confidence')}).")
    if ai and ai.get("knowledge_claims"):
        c.append("Some AI reasoning relies on general knowledge not checked by this tool: "
                 + "; ".join(map(str, ai["knowledge_claims"]))[:600])
    if ai and (ai.get("action") or "keep") != "keep" and not mig:
        c.append("Migration was recommended but not executed in this run.")
    if mig:
        if mig.get("status") != "verified":
            c.append(f"Migration is NOT verified (status: {mig.get('status')}). {mig.get('error') or ''}".strip())
        runtime_files = {u["file"] for u in dep["usage"] if not u["file"].startswith("tests")}
        if mig.get("status") == "verified" and runtime_files:
            c.append("Passing tests only prove the behaviour the test suite exercises; code paths in "
                     f"{', '.join(sorted(runtime_files))} not covered by tests remain unverified.")
    if not dep["usage"]:
        c.append("Dependency is not imported by the repository's source; it may be used by tooling, "
                 "a Makefile, or at runtime by another package — check before removal.")
    return c


def _dedupe_usage(usage: list[dict]) -> list[dict]:
    seen, out = set(), []
    for u in usage:
        if u["kind"] == "reference":
            continue
        key = (u["file"], u["line"], u["kind"])
        if key in seen:
            continue
        seen.add(key)
        out.append(u)
    return out


def build_capsules(data: dict) -> list[dict]:
    caps = []
    for name, dep in sorted(data["inventory"].items(),
                            key=lambda kv: ({"high": 0, "medium": 1, "low": 2, "none": 3}[kv[1]["observed_risk"]], kv[0])):
        ai = data["ai"].get(name)
        chk = data["ai_checks"].get(name, {})
        mig = data["migrations"].get(name)
        p = dep.get("pypi", {})
        last = (mig or {}).get("attempts", [{}])[-1] if mig and mig.get("attempts") else None
        caps.append({
            "dependency": name,
            "status": (mig or {}).get("status") or ("recommendation_only" if ai and ai.get("action") != "keep"
                                                    else "no_action" if ai else "observed_only"),
            "observed": {
                "_provenance": "OBSERVED",
                "dependency_details": {
                    "declared": dep["declared"], "installed_version_in_baseline": dep["installed_version"],
                    "import_names": dep["modules"], "latest_version": p.get("latest_version"),
                    "latest_released": p.get("latest_released"), "last_release_days": p.get("last_release_days"),
                    "pypi_summary": p.get("summary"), "pypi_url": p.get("source_url"),
                    "github": p.get("github"), "installed_release": p.get("installed"),
                },
                "observed_risk": dep["observed_risk"],
                "risk_indicators": dep["indicators"],
                "usage_locations": _dedupe_usage(dep["usage"]),
            },
            "ai_recommendation": None if not ai else {
                "_provenance": "AI",
                "risk_level": ai.get("risk_level"), "risk_summary": ai.get("risk_summary"),
                "action": ai.get("action"), "proposed_replacement": ai.get("replacement"),
                "rationale": ai.get("rationale"), "migration_steps": ai.get("migration_steps"),
                "suggested_tests": ai.get("suggested_tests"),
                "expected_compatibility_gaps": ai.get("expected_compatibility_gaps"),
                "cited_indicators": ai.get("cited_indicators"), "knowledge_claims": ai.get("knowledge_claims"),
                "confidence": ai.get("confidence"),
            },
            "ai_claim_verification": {"_provenance": "OBSERVED", **chk} if chk else None,
            "execution": None if not mig else {
                "_provenance": "VERIFIED",
                "baseline_original": data["baseline"]["summary"],
                "equivalence_test_on_original": (last or {}).get("equivalence_on_original", {}) and
                    last["equivalence_on_original"].get("summary"),
                "candidate_replacement": (last or {}).get("candidate_run", {}) and last["candidate_run"].get("summary"),
                "equivalence_test_on_replacement": (last or {}).get("equivalence_on_replacement") and
                    last["equivalence_on_replacement"].get("summary"),
                "equivalence_test_valid": mig.get("equivalence_valid"),
                "comparison": (last or {}).get("comparison"),
                "fix_attempts": len(mig.get("attempts", [])) - 1 if mig.get("attempts") else 0,
                "attempts": mig.get("attempts"),
                "changed_files": mig.get("changed_files"),
                "patch_file": f"patches/{name}.patch" if mig.get("diff") else None,
                "equivalence_test_file": f"tests/{Path(mig['equivalence_test']['path']).name}"
                    if (mig.get("equivalence_test") or {}).get("content") else None,
                "error": mig.get("error"),
            },
            "compatibility_gaps": {
                "observed": {"_provenance": "VERIFIED", "items": _gaps_observed(mig)},
                "expected_by_ai": {"_provenance": "AI", "items": (ai or {}).get("expected_compatibility_gaps") or []},
            },
            "open_concerns_and_limitations": _concerns(dep, ai, chk, mig),
        })
    return caps


def write_all(out: Path, data: dict) -> list[Path]:
    caps = build_capsules(data)
    (out / "patches").mkdir(exist_ok=True)
    (out / "tests").mkdir(exist_ok=True)
    for name, mig in (data.get("migrations") or {}).items():
        if mig.get("diff"):
            (out / "patches" / f"{name}.patch").write_text(mig["diff"], encoding="utf-8")
        eq = mig.get("equivalence_test") or {}
        if eq.get("content"):
            (out / "tests" / Path(eq["path"]).name).write_text(eq["content"], encoding="utf-8")
    comb = data.get("combined") or {}
    if comb.get("diff"):
        (out / "patches" / "combined.patch").write_text(comb["diff"], encoding="utf-8")

    doc = {
        "schema": "dependency-exit-capsule/1.0",
        "provenance_legend": PROVENANCE,
        "generated_by": data["tool"], "started_at": data["started_at"], "finished_at": data["finished_at"],
        "target_repository": data["repository"],
        "python_target": data["python_target"], "host_python": data["host_python"],
        "ai_model": data.get("model"),
        "baseline_run": {"_provenance": "VERIFIED", **(data["baseline"] or {})},
        "alternate_manifest_runs": [{"_provenance": "VERIFIED", **v} for v in data["variants"]],
        "manifests": {"_provenance": "OBSERVED", **data["manifests"]},
        "summary": _summary(caps, data),
        "capsules": caps,
        "combined_migration": None if not comb else {
            "_provenance": "VERIFIED", "status": comb.get("status"), "reason": comb.get("reason"),
            "comparison": comb.get("comparison"), "run": comb.get("run"),
            "edit_conflicts": comb.get("edit_conflicts"),
            "patch_file": "patches/combined.patch" if comb.get("diff") else None},
        "reproduce": _reproduce(data),
    }
    paths = []
    p = out / "capsule.json"
    p.write_text(json.dumps(doc, indent=2, default=str), encoding="utf-8"); paths.append(p)
    p = out / "ai_transcript.jsonl"
    p.write_text("\n".join(json.dumps(t, default=str) for t in data.get("ai_transcript", [])), encoding="utf-8")
    paths.append(p)
    p = out / "capsule.md"
    p.write_text(render_markdown(doc), encoding="utf-8"); paths.append(p)
    p = out / "report.html"
    patches = {n: m.get("diff") for n, m in (data.get("migrations") or {}).items() if m.get("diff")}
    p.write_text(render_html({**doc, "__patches": patches}), encoding="utf-8"); paths.append(p)
    p = out / "replay.sh"
    p.write_text(_replay_sh(data), encoding="utf-8"); p.chmod(0o755); paths.append(p)
    return paths


def _summary(caps, data):
    s = {"dependencies_analysed": len(caps),
         "observed_risk": {k: sum(c["observed"]["observed_risk"] == k for c in caps) for k in ("high", "medium", "low", "none")},
         "migrations_attempted": sum(1 for c in caps if c["execution"]),
         "migrations_verified": sum(1 for c in caps if c["status"] == "verified"),
         "migrations_unresolved": sum(1 for c in caps if c["status"] in ("unresolved", "failed", "error")),
         "baseline_tests": data["baseline"]["summary"],
         "ai_ungrounded_claims": sum(1 for c in caps if (c["ai_claim_verification"] or {}).get("grounded") is False)}
    comb = data.get("combined") or {}
    if comb.get("run"):
        s["combined_tests"] = comb["run"]["summary"]
    return s


def _reproduce(data):
    repo = data["repository"]
    return {
        "steps": [
            f"git clone {repo.get('remote') or repo.get('input')} repo && cd repo && git checkout {repo.get('commit')}",
            f"uv venv -p {data['python_target']} .venv && uv pip install -p .venv/bin/python " +
            " ".join(f"-r {f}" for f in data["manifests"]["files"] if f.endswith('.txt')),
            ".venv/bin/python -m pytest -q   # original (baseline)",
            "git apply ../capsule/patches/combined.patch   # or a single patches/<dep>.patch",
            "re-run the install + pytest commands above   # replacement",
        ],
        "script": "replay.sh",
    }


def _replay_sh(data):
    repo = data["repository"]
    reqs = " ".join(f"-r {f}" for f in data["manifests"]["files"] if f.endswith(".txt")) or "-e ."
    return f"""#!/usr/bin/env bash
# Re-run the verification in this capsule on your own machine.
# usage: ./replay.sh [patch]   (default: patches/combined.patch)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
PATCH="${{1:-$HERE/patches/combined.patch}}"
WORK="$(mktemp -d)"
git clone -q {repo.get('remote') or repo.get('input')} "$WORK/repo"
cd "$WORK/repo"
{"git checkout -q " + repo["commit"] if repo.get("commit") else "true"}
echo "== ORIGINAL dependencies =="
uv venv -q -p {data['python_target']} .venv-orig
uv pip install -q -p .venv-orig/bin/python {reqs}
.venv-orig/bin/python -m pip --version >/dev/null 2>&1 || true
PYTHONPATH=. .venv-orig/bin/python -m pytest -q -p no:cacheprovider || true
echo "== REPLACEMENT dependencies ($PATCH) =="
git apply "$PATCH"
uv venv -q -p {data['python_target']} .venv-new
uv pip install -q -p .venv-new/bin/python {reqs} pytest
PYTHONPATH=. .venv-new/bin/python -m pytest -q -p no:cacheprovider
"""


